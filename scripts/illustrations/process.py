"""
Turns the generated exercise illustrations (1024px PNG from Figma AI) into app assets:
auto-crops each to the figure + equipment, then writes
  assets/exillu/<id>.webp        640px, for the exercise page
  assets/exillu/thumb/<id>.webp  192px, tighter crop, for round list thumbnails
and regenerates src/data/exerciseIllustrations.ts.

Usage: python3 scripts/illustrations/process.py <raw-png-dir> [skip-id ...]
"""
import os
import sys

from PIL import Image, ImageChops

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'assets', 'exillu')
BG = (242, 238, 230)


def bbox(im):
    bg = Image.new('RGB', im.size, BG)
    diff = ImageChops.difference(im, bg).convert('L').point(lambda v: 255 if v > 26 else 0)
    return diff.getbbox() or (0, 0, im.width, im.height)


def square(im, box, pad):
    x0, y0, x1, y1 = box
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    side = max(x1 - x0, y1 - y0) * (1 + pad)
    side = min(side, max(im.width, im.height) * 1.2)
    half = side / 2
    canvas = Image.new('RGB', (int(side), int(side)), BG)
    canvas.paste(im, (int(half - cx), int(half - cy)))
    return canvas


def main():
    raw = sys.argv[1]
    skip = set(sys.argv[2:])
    os.makedirs(os.path.join(OUT, 'thumb'), exist_ok=True)
    ids = sorted(f[:-4] for f in os.listdir(raw) if f.endswith('.png') and f[:-4] not in skip)
    total = 0
    for i in ids:
        im = Image.open(os.path.join(raw, f'{i}.png')).convert('RGB')
        box = bbox(im)
        full = square(im, box, 0.12).resize((640, 640), Image.LANCZOS)
        full.save(os.path.join(OUT, f'{i}.webp'), 'WEBP', quality=80, method=6)
        thumb = square(im, box, 0.04).resize((192, 192), Image.LANCZOS)
        thumb.save(os.path.join(OUT, 'thumb', f'{i}.webp'), 'WEBP', quality=80, method=6)
        total += os.path.getsize(os.path.join(OUT, f'{i}.webp')) + os.path.getsize(os.path.join(OUT, 'thumb', f'{i}.webp'))
    present = sorted(f[:-5] for f in os.listdir(OUT) if f.endswith('.webp'))
    lines = [
        '// AUTO-GENERATED by scripts/illustrations/process.py — exercise illustrations (Figma AI).',
        'export const EXERCISE_ILLUSTRATIONS: Record<string, { full: number; thumb: number }> = {',
        *[f"  {i}: {{ full: require('../../assets/exillu/{i}.webp'), thumb: require('../../assets/exillu/thumb/{i}.webp') }}," for i in present],
        '};',
        '',
    ]
    with open(os.path.join(ROOT, 'src', 'data', 'exerciseIllustrations.ts'), 'w') as f:
        f.write('\n'.join(lines))
    print(f'processed {len(ids)}, total {len(present)}, {total // 1024} KB')


if __name__ == '__main__':
    main()
