"""
Downloads demo photos for exercises from the public-domain free-exercise-db
(https://github.com/yuhonas/free-exercise-db, Unlicense), converts them to a
monochrome dark-UI friendly style and writes src/data/exerciseImages.ts.

Usage: python3 scripts/fetch_images.py <cache_dir>
"""
import io, os, re, sys, urllib.request
from PIL import Image, ImageOps, ImageEnhance

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '.cache-img')
OUT = os.path.join(ROOT, 'assets', 'exercises')
BASE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/'
os.makedirs(CACHE, exist_ok=True)
os.makedirs(OUT, exist_ok=True)

pairs = []
for f in ['ex_upper.ts', 'ex_arms.ts', 'ex_lower.ts']:
    src = open(os.path.join(ROOT, 'src', 'data', f), encoding='utf-8').read()
    chunks = re.split(r"\bex\('", src)[1:]
    for ch in chunks:
        ex_id = ch.split("'", 1)[0]
        m = re.search(r"img: '([^']+)'", ch)
        if m:
            pairs.append((ex_id, m.group(1)))

def fetch(folder, n):
    p = os.path.join(CACHE, f'{folder}__{n}.jpg')
    if not os.path.exists(p):
        with urllib.request.urlopen(BASE + folder + f'/{n}.jpg', timeout=30) as r:
            data = r.read()
        open(p, 'wb').write(data)
    return p

def process(src, dst):
    im = Image.open(src).convert('L')
    im = ImageOps.autocontrast(im, cutoff=1)
    w = 480
    h = int(im.height * w / im.width)
    im = im.resize((w, h), Image.LANCZOS)
    im = ImageEnhance.Contrast(im).enhance(1.08)
    # compress highlights so white studio backgrounds don't glare in the dark UI
    im = im.point(lambda v: int(14 + v * 0.80))
    im.save(dst, 'JPEG', quality=62, optimize=True, progressive=True)

ok = []
for ex_id, folder in pairs:
    try:
        for n in (0, 1):
            process(fetch(folder, n), os.path.join(OUT, f'{ex_id}_{n}.jpg'))
        ok.append(ex_id)
    except Exception as e:  # noqa
        print('skip', ex_id, folder, e)

lines = ['// AUTO-GENERATED by scripts/fetch_images.py — demo photos from free-exercise-db (public domain).',
         'export const EXERCISE_IMAGES: Record<string, [number, number]> = {']
for ex_id in ok:
    lines.append(f"  '{ex_id}': [require('../../assets/exercises/{ex_id}_0.jpg'), require('../../assets/exercises/{ex_id}_1.jpg')],")
lines.append('};')
open(os.path.join(ROOT, 'src', 'data', 'exerciseImages.ts'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('images:', len(ok), 'of', len(pairs))
